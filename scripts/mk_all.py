#!/usr/bin/env python3
"""Regenerate the root import file `Linglib.lean` from the tracked modules.

Usage:
    python3 scripts/mk_all.py          # rewrite Linglib.lean
    python3 scripts/mk_all.py --check  # exit 1 if Linglib.lean misses a tracked module or lists an untracked one

The lakefile builds the library from `globs := #[.submodules `Linglib]`, so the root import list
is not a build input: it serves `import Linglib` for downstream users and the doc-gen root page.
Pull requests leave it alone (two requests inserting adjacent lines conflicted on nothing else),
and it is regenerated here before a release.

Dependencies: pure stdlib + `git`.
"""
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = """/-!
# Linglib

The root import of the library: every tracked module, regenerated by `scripts/mk_all.py`.
-/
"""


def tracked_modules() -> list[str]:
    out = subprocess.check_output(["git", "ls-files", "Linglib"], cwd=ROOT, text=True)
    mods = []
    for line in out.splitlines():
        if line.endswith(".lean"):
            mods.append(".".join(Path(line).with_suffix("").parts))
    return sorted(mods)


def listed_modules(text: str) -> set[str]:
    return {l[len("import "):].strip() for l in text.splitlines() if l.startswith("import ")}


def main() -> int:
    root = ROOT / "Linglib.lean"
    mods = tracked_modules()
    if "--check" in sys.argv:
        listed = listed_modules(root.read_text(encoding="utf-8")) if root.exists() else set()
        missing = sorted(set(mods) - listed)
        stale = sorted(listed - set(mods))
        for m in missing:
            sys.stderr.write(f"[check] missing from Linglib.lean: {m}\n")
        for m in stale:
            sys.stderr.write(f"[check] not tracked but listed in Linglib.lean: {m}\n")
        if missing or stale:
            return 1
        sys.stdout.write(f"OK: Linglib.lean lists all {len(mods)} tracked modules\n")
        return 0
    root.write_text(HEADER + "".join(f"import {m}\n" for m in mods), encoding="utf-8")
    sys.stdout.write(f"[gen] Linglib.lean ← {len(mods)} tracked modules\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
